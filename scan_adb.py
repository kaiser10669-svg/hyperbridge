import socket

ips = [
    "192.168.1.33", "192.168.1.47", "192.168.1.50", "192.168.1.51",
    "192.168.1.61", "192.168.1.64", "192.168.1.79", "192.168.1.83",
    "192.168.1.85", "192.168.1.88", "192.168.1.90", "192.168.1.93",
    "192.168.1.98", "192.168.1.109", "192.168.1.114", "192.168.1.116",
    "192.168.1.120", "192.168.1.121", "192.168.1.130", "192.168.1.137",
    "192.168.1.149"
]

print("Scanning for open ADB port 5555...")
for ip in ips:
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.settimeout(0.1)
    res = s.connect_ex((ip, 5555))
    if res == 0:
        print(f"FOUND ADB PORT 5555 ON: {ip}")
    s.close()
print("Done.")
